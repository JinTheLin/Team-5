"""
Makes the cane's voice clips with the Mac's built-in text-to-speech and
packs them into the sketch, so they're stored in the ESP32's own memory.

    python3 make_clips.py                       # default voice (Samantha)
    python3 make_clips.py --voice Reed          # another voice (list: say -v '?')
    python3 make_clips.py --sketch "/path/to/CameraWebServer"   # also update that sketch

Writes:
    voice/clips/*.wav           16 kHz mono WAVs (to listen to: afplay clips/chair.wav)
    <sketch>/src/voice_clips.h  clip table for the firmware
    <sketch>/src/voice_clips.cpp  clip data (8-bit mu-law, 16 kHz) - big file, don't edit

After running it, click Upload in Arduino IDE. Files in the sketch's src/ folder
are compiled but don't show up as tabs.

The cane builds each sentence by playing clips back to back, e.g.
    "chair" + "less_than_one_meter" + "caution"
    "stairs" + "three" + "meters"
    "stairs" + "ahead" + "caution"

Object words come from WATCH in Computer Vision/cane_logic.py, so every object
the laptop/phone can warn about has a clip. Re-run this after changing WATCH.
"""

import argparse
import array
import subprocess
import sys
import wave
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "clips"
REPO_SKETCH = HERE.parent  # Hardware/esp32
sys.dont_write_bytecode = True
sys.path.insert(0, str(HERE.parents[2] / "Computer Vision"))  # Pocket-Miracle/Computer Vision
from cane_logic import WATCH  # noqa: E402

SAMPLE_RATE = 16000

# file / clip name -> what is spoken
PHRASES = {
    # distances
    "less_than_one_meter": "less than one meter",
    "one": "one", "two": "two", "three": "three", "four": "four", "five": "five",
    "meter": "meter",
    "meters": "meters",
    # endings
    "ahead": "ahead",
    "caution": "caution",
    # system messages
    "cane_on": "cane on",
    "cane_off": "cane off",
    "sonar_mode": "sonar mode",
    "camera_mode": "camera mode",
    "speaker_muted": "speaker muted",      # double-tap the switch
    "speaker_unmuted": "speaker unmuted",
}
for word in sorted(set(WATCH.values())):
    PHRASES[word] = word


def read_wav(path):
    with wave.open(str(path)) as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2 and w.getframerate() == SAMPLE_RATE
        samples = array.array("h", w.readframes(w.getnframes()))
    if sys.byteorder == "big":
        samples.byteswap()
    return list(samples)


def trim_and_normalize(samples, pad_ms=25, peak_target=0.95):
    """Cuts the silence before/after the word and makes it as loud as possible."""
    peak = max((abs(s) for s in samples), default=0)
    if peak == 0:
        return samples
    threshold = peak * 0.02
    loud = [i for i, s in enumerate(samples) if abs(s) > threshold]
    pad = SAMPLE_RATE * pad_ms // 1000
    start = max(0, loud[0] - pad)
    end = min(len(samples), loud[-1] + pad)
    gain = peak_target * 32767 / peak
    return [max(-32768, min(32767, int(s * gain))) for s in samples[start:end]]


def ulaw_encode(sample):
    """16-bit sample -> 8-bit mu-law (G.711). Keeps speech quality at half the size."""
    BIAS, CLIP = 0x84, 32635
    sign = 0x80 if sample < 0 else 0
    sample = min(abs(sample), CLIP) + BIAS
    exponent = max(0, min(7, sample.bit_length() - 8))
    mantissa = (sample >> (exponent + 3)) & 0x0F
    return ~(sign | (exponent << 4) | mantissa) & 0xFF


def ulaw_decode(u):
    """Same math as the firmware (voice.cpp), used to self-check."""
    u = ~u & 0xFF
    exponent, mantissa = (u >> 4) & 0x07, u & 0x0F
    sample = (((mantissa << 3) + 0x84) << exponent) - 0x84
    return -sample if u & 0x80 else sample


def c_name(name):
    return "clip_" + "".join(ch if ch.isalnum() else "_" for ch in name)


def write_firmware_files(clips, sketch_dir):
    src = Path(sketch_dir) / "src"
    src.mkdir(parents=True, exist_ok=True)

    (src / "voice_clips.h").write_text(
        "// Generated by Hardware/esp32/voice/make_clips.py - don't edit by hand.\n"
        "#pragma once\n"
        "#include <stdint.h>\n"
        "#include <stddef.h>\n\n"
        f"#define VOICE_SAMPLE_RATE {SAMPLE_RATE}\n\n"
        "struct VoiceClip {\n"
        "  const char *name;     // e.g. \"chair\", \"less_than_one_meter\"\n"
        "  const uint8_t *data;  // 8-bit mu-law samples\n"
        "  uint32_t length;      // number of samples\n"
        "};\n\n"
        "extern const VoiceClip VOICE_CLIPS[];\n"
        "extern const size_t VOICE_CLIP_COUNT;\n"
    )

    lines = ["// Generated by Hardware/esp32/voice/make_clips.py - don't edit by hand.",
             "// 8-bit mu-law, 16 kHz mono. Stored in flash (const).",
             '#include "voice_clips.h"', ""]
    for name, data in clips:
        lines.append(f"static const uint8_t {c_name(name)}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("const VoiceClip VOICE_CLIPS[] = {")
    for name, data in clips:
        lines.append(f'  {{"{name}", {c_name(name)}, {len(data)}}},')
    lines.append("};")
    lines.append("const size_t VOICE_CLIP_COUNT = sizeof(VOICE_CLIPS) / sizeof(VOICE_CLIPS[0]);")
    (src / "voice_clips.cpp").write_text("\n".join(lines) + "\n")
    return src


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", default="Samantha")
    ap.add_argument("--rate", type=int, default=175, help="words per minute")
    ap.add_argument("--sketch", action="append", default=[],
                    help="extra sketch folder to update (e.g. the one Arduino IDE opens)")
    args = ap.parse_args()

    # Self-check the mu-law math before using it
    for s in (-32768, -1000, -1, 0, 1, 1000, 32767):
        assert abs(ulaw_decode(ulaw_encode(s)) - max(-32635, min(32635, s))) <= 1024

    OUT.mkdir(exist_ok=True)
    clips = []
    for name, text in PHRASES.items():
        path = OUT / f"{name}.wav"
        subprocess.run(["say", "-v", args.voice, "-r", str(args.rate), "-o", str(path),
                        f"--data-format=LEI16@{SAMPLE_RATE}", text], check=True)
        samples = trim_and_normalize(read_wav(path))
        clips.append((name, bytes(ulaw_encode(s) for s in samples)))

    total = sum(len(d) for _, d in clips)
    print(f"{len(clips)} clips, {total / 1024:.0f} KB in flash, "
          f"{total / SAMPLE_RATE:.1f} s of audio")
    for sketch in [REPO_SKETCH] + args.sketch:
        print(f"  wrote {write_firmware_files(clips, sketch)}")


if __name__ == "__main__":
    main()
